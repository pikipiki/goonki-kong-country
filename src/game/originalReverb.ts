function presentationPlatforms(): Platform[] {
  const platforms: Platform[] = []
  for (let column = 0; column < CAVE_COLUMNS; column++) {
    const x = column * 32 + 16
    let span: {
      bottom: number
      top: number
    } | null = null
    const spans: {
      bottom: number
      top: number
    }[] = []
    for (let row = 15; row >= 0; row--) {
      const cell = caveTerrainCellSNES(x, row)
      if (!cell) {
        continue
      }
      const bottom = (15 - row) * 32
      if (span && bottom <= span.top + 1) {
        span.top = Math.max(span.top, cell.floorY)
      } else {
        span = { bottom, top: cell.floorY }
        spans.push(span)
      }
    }
    for (const item of spans) {
      platforms.push({
        x: (x - ROM_WORLD_X) / 32,
        y: (item.top - 175) / 32,
        w: 1,
        h: Math.max(0.1, (item.top - item.bottom) / 32),
        kind: 'stone',
      })
    }
  }
  return platforms
}
